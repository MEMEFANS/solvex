import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {parseUnits} from 'ethers';
import {createWalletService} from '../src/wallet-service.js';
import {closeDatabase} from '../src/database.js';
import {createATokenService} from '../src/a-token-service.js';
import {createATokenPendingService} from '../src/a-token-pending-service.js';
import {createATokenNodeService} from '../src/a-token-node-service.js';
import {createATokenStakingService} from '../src/a-token-staking-service.js';
import {createATokenTeamService} from '../src/a-token-team-service.js';
import {createATokenShareholderService} from '../src/a-token-shareholder-service.js';
import {createATokenMatchPoolService} from '../src/a-token-match-pool-service.js';
import {createATokenBlindBoxService} from '../src/a-token-blindbox-service.js';
const A=n=>parseUnits(String(n),18), U=n=>parseUnits(String(n),6), DAY=86400000;
const address=n=>'0x'+n.toString(16).padStart(40,'0');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'solvex-model-'));
let now=Date.UTC(2026,10,10); const clock=()=>now;
try {
 const wallet=createWalletService({dataRoot:root,depositAddress:address(999),networks:[]}); const db=wallet.database;
 const at=createATokenService({database:db,walletService:wallet,clock});
 const pending=createATokenPendingService({aTokenService:at,database:db,clock});
 const team=createATokenTeamService({database:db,walletService:wallet,pendingService:pending,clock});
 const options={aTokenService:at,database:db,pendingService:pending,teamService:team,clock};
 const node=createATokenNodeService(options), energy=createATokenStakingService(options);
 const shareholders=createATokenShareholderService({...options,walletService:wallet});
 const drive=createATokenMatchPoolService({...options,shareholderService:shareholders});
 const blind=createATokenBlindBoxService({...options,randomCoins:()=>300n});
 const user=address(1); wallet.ensureUser(user); at.creditUsdt(user,U(10000));
 db.creditATokenZone({wallet:user,zone:'alpha',units:A(20000),bizType:'test',refId:'seed',createdAt:now});
 assert.equal(at.TOTAL_SUPPLY,A(1000000000)); assert.equal(at.BURN_CAP,A(900000000));
 assert.throws(()=>at.assertFreeTrading(),/平台流动性准备金/);
 assert.equal(at.liquidityStatus().enabled,false);
 assert.equal(at.liquidityStatus().status,'pending');
 at.setFreeTradingEnabled(true);
 assert.equal(at.liquidityStatus().enabled,false,'开关不能绕过50万准备金门槛');
 db.insertATokenLpPoolEntryRow({id:'threshold-test',source:'adjustment',refId:'threshold-test',usdtUnits:U(500000).toString(),direction:'in',createdAt:now});
 assert.equal(at.liquidityStatus().enabled,true);
 assert.equal(at.liquidityStatus().status,'open');
 at.assertFreeTrading();
 at.setFreeTradingEnabled(false);
 assert.equal(at.liquidityStatus().enabled,false);
 for(const [amount,rate] of [[1999,25],[2000,45],[9999,45],[10000,55]]) assert.equal(node.quote(String(amount)).ratePct,rate);
 const opened=node.open(user,'1000'); assert.equal(pending.list(user).length,0);
 now+=DAY; node.processAll(); let reward=pending.list(user).find(r=>r.bizType==='node'); assert.equal(BigInt(reward.amountUnits),A(250)/30n);
 assert.equal(reward.availableAt,now); assert.equal(reward.expiresAt,now+DAY); pending.claim(user,reward.id); assert.throws(()=>pending.claim(user,reward.id),/处理/);
 now+=DAY; node.processAll(); reward=pending.list(user).find(r=>r.bizType==='node'); now+=DAY; assert.throws(()=>pending.claim(user,reward.id),/过期/);
 now=opened.expiresAt; node.processAll(); const principal=pending.list(user,'pending',1000).find(r=>r.periodKey==='principal'); assert.equal(BigInt(principal.amountUnits),A(1000));
 now+=5*DAY; pending.claim(user,principal.id); assert.equal(db.getATokenNode(opened.id).status,'completed');
 const e=energy.grantEnergy(user,'1000',{requestId:'energy_test_1',reason:'工作室测试'});
 assert.equal(energy.grantEnergy(user,'1000',{requestId:'energy_test_1',reason:'工作室测试'}).id,e.id); assert.throws(()=>energy.stake(user,'current','100'),/质押套餐无效/);
 now+=DAY; energy.processAll(); let er=pending.list(user).find(r=>r.bizId===e.id); assert.equal(BigInt(er.amountUnits),A(10)); pending.claim(user,er.id);
 now+=99*DAY; energy.processAll(); const ev=energy.present(user).find(r=>r.id===e.id); assert.equal(ev.status,'completed'); assert.equal(ev.totalEarned,'1000.0'); assert.equal(ev.interestEarned,'0');
 const box=blind.join({wallet:user,refId:'box1'}); assert.equal(pending.list(user).filter(r=>r.bizId===box.id).length,0); now+=DAY; blind.processDue(); const br=pending.list(user).find(r=>r.bizId===box.id); assert.equal(BigInt(br.amountUnits),A(10)); assert.equal(br.availableAt,now);
 db.creditATokenZone({wallet:user,zone:'alpha',units:A(2000).toString(),bizType:'test',refId:'drive-alpha'}); db.creditATokenZone({wallet:user,zone:'beta',units:A(2000).toString(),bizType:'test',refId:'drive-beta'}); const ent=drive.enterPool({wallet:user,amount:'100'}); assert.equal(ent.durationHours,24); assert.throws(()=>drive.enterPool({wallet:user,amount:'100'}),/每日仅/); assert.equal(drive.overview(user).usedToday,true);
 now+=DAY; drive.releaseDue(); assert.equal(BigInt(db.getATokenUsableQuota(user).releasedUnits),A(200)); const e2=drive.enterPool({wallet:user,amount:'100'}); assert.equal(e2.durationHours,48); assert.equal(drive.durationHoursFor(ent.createdAt,now+50*DAY),720);
 assert.throws(()=>shareholders.join({wallet:user,tier:'t1000',refId:'s1000'}),/未开放/); shareholders.join({wallet:user,refId:'s500'});
 shareholders.recordFee({source:'buy_fee',refId:'fee1',wallet:user,usdtUnits:U(4000).toString()}); shareholders.distributeClosedPools(); assert.ok(db.getActiveATokenShareholderMember(user),'未到30天不能撤回');
 assert.equal(db.listATokenShareholderPoolsByTier('t1000',100).some(p=>p.status==='settled'),false);
 now+=30*DAY; shareholders.distributeClosedPools(); assert.ok(!db.getActiveATokenShareholderMember(user),'30天未达到V3撤回');
 assert.equal(team.settleParityRewards().settled,false);
 console.log('PASS Solvex: supply/LP gate, pool daily interest/principal, expiry/idempotency, energy 100 releases, blindbox UTC day, drive schedule/daily cap, shareholder reserve/deadline.');
} finally {closeDatabase(root); fs.rmSync(root,{recursive:true,force:true});}

