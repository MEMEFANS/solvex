import fs from 'node:fs/promises';
import postcss from 'postcss';
import { pathToFileURL } from 'node:url';
// Only selectors explicitly scoped to legacy page components can be deferred.
// Mixed/global selectors, wallet controls and persistent page wrappers remain.
const legacy = /\.(?:earn|miner|stake|act|leaderboard|team|terminal|trade|order|book|aentry|atrade|awd|ts|pool|referral|ai|log|asset|perp|spot|market)-|\.portal-(?!page\b)/;
export async function buildShellStyles(root = new URL('../', import.meta.url)) {
  const source = await fs.readFile(new URL('public/styles/critical.css', root), 'utf8');
  const ast = postcss.parse(source);
  let deferredRules = 0;
  ast.walkRules(rule => {
    if (postcss.list.comma(rule.selector).every(selector => !/:(?:not|is|where|has)\(/.test(selector) && legacy.test(selector))) { rule.remove(); deferredRules++; }
  });
  ast.walkComments(comment => comment.remove());
  ast.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
  const output = '/* Generated by scripts/build-shell-styles.mjs. Full legacy styles load with legacy routes. */\n' + ast.toString();
  await fs.writeFile(new URL('public/styles/react-shell.css', root), output);
  return { originalBytes: Buffer.byteLength(source), shellBytes: Buffer.byteLength(output), deferredRules };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) console.log(JSON.stringify(await buildShellStyles()));
